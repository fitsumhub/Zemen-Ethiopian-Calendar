  static String get(String key, AppLanguage language) {
    final Map<String, String> map;
    switch (language) {
      case AppLanguage.amharic:
        map = _amharicMap;
        break;
      case AppLanguage.oromo:
        map = _oromoMap;
        break;
      case AppLanguage.tigrinya:
        map = _tigrinyaMap;
        break;
      case AppLanguage.french:
        map = _frenchMap;
        break;
      case AppLanguage.english:
        map = _englishMap;
        break;
    }
    return map[key] ?? _englishMap[key] ?? key;
  }

  /// Replace `{name}` style placeholders in a translated string.
  static String format(
    String key,
    AppLanguage language, {
    Map<String, String> params = const {},
  }) {
    var value = get(key, language);
    params.forEach((k, v) {
      value = value.replaceAll('{$k}', v);
    });
    return value;
  }

